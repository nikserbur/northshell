const dictionaries: Record<Language, Record<I18nKey, string>> = { ru, en }

export type Translate = (key: I18nKey, vars?: Record<string, string | number>) => string

export function makeT(lang: Language): Translate {
  const dict = dictionaries[lang] ?? ru
  return (key, vars) => {
    let s: string = dict[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
}
