/** Pure helpers for HTTP environments: a local shell with $BASE_URL, $TOKEN and default curl headers. */

export interface HeaderLine {
  name: string
  value: string
}

/** RFC 9110 token characters for header names. */
const HEADER_NAME_RE = /^[A-Za-z0-9!#$%&'*+.^_`|~-]+$/
const CONTROL_RE = /[\x00-\x08\x0a-\x1f\x7f]/

/** Parses `Name: value` lines. Blank lines and `#` comments are skipped; bad lines are reported 1-based. */
export function parseHeaders(text: string): { headers: HeaderLine[]; invalid: number[] } {
  const headers: HeaderLine[] = []
  const invalid: number[] = []
  text.split('\n').forEach((raw, i) => {
    const line = raw.replace(/\r$/, '').trim()
    if (!line || line.startsWith('#')) return
    const colon = line.indexOf(':')
    const name = colon > 0 ? line.slice(0, colon).trim() : ''
    const value = colon > 0 ? line.slice(colon + 1).trim() : ''
    if (!HEADER_NAME_RE.test(name) || CONTROL_RE.test(value)) invalid.push(i + 1)
    else headers.push({ name, value })
  })
  return { headers, invalid }
}

/**
 * Accepts only http(s) URLs without embedded credentials (those belong in the Keychain token).
 * Returns the URL without a trailing slash, so `$BASE_URL/path` works.
 */
export function normalizeBaseUrl(input: string): string | null {
  let url: URL
  try {
    url = new URL(input.trim())
  } catch {
    return null
  }
  if ((url.protocol !== 'http:' && url.protocol !== 'https:') || !url.hostname) return null
  if (url.username || url.password) return null
  return url.toString().replace(/\/+$/, '')
}

/** Host and port a base URL points at (used for the session list and sorting). */
export function endpointOf(baseUrl: string): { host: string; port: number } | null {
  const normalized = normalizeBaseUrl(baseUrl)
  if (!normalized) return null
  const url = new URL(normalized)
  return { host: url.hostname, port: url.port ? Number(url.port) : url.protocol === 'https:' ? 443 : 80 }
}

const TOKEN_RE = /\$\{TOKEN\}|\$TOKEN\b/g

export function usesToken(value: string): boolean {
  return new RegExp(TOKEN_RE.source).test(value)
}

/** Substitutes $TOKEN / ${TOKEN}; returns null when the token is needed but not set. */
export function expandToken(value: string, token: string | undefined): string | null {
  if (!usesToken(value)) return value
  return token ? value.replace(TOKEN_RE, () => token) : null
}

/** Double-quoted curl config string: backslashes and quotes escaped. */
function quote(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

export interface CurlrcInput {
  headers: HeaderLine[]
  token?: string
  insecure: boolean
  /** The user's own ~/.curlrc, kept so their defaults still apply. */
  userConfig?: string
}

/**
 * Builds the curl config read via $CURL_HOME/.curlrc. Headers whose $TOKEN cannot be resolved are
 * left out and returned in `skipped`, so the shell does not send a literal "$TOKEN".
 */
export function buildCurlrc({ headers, token, insecure, userConfig }: CurlrcInput): { text: string; skipped: string[] } {
  const lines: string[] = ['# Generated by Northshell for an HTTP environment; deleted when the tab closes.']
  if (userConfig?.trim()) lines.push('', '# --- your ~/.curlrc ---', userConfig.trimEnd(), '# ---', '')
  const skipped: string[] = []
  for (const h of headers) {
    const value = expandToken(h.value, token)
    if (value === null) skipped.push(h.name)
    else lines.push(`header = ${quote(`${h.name}: ${value}`)}`)
  }
  if (insecure) lines.push('insecure')
  return { text: `${lines.join('\n')}\n`, skipped }
}
